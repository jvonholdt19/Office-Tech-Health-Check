// The change set: the plan's day-one DNS changes as before/after values per name and type, which is
// what the technician reviews and confirms. Read-only: nothing here (or anywhere in this tool)
// writes to a DNS provider or registrar. Confirming only unlocks the copy-ready values.

import { createHash } from "node:crypto";

const norm = (v) => String(v ?? "").replace(/\s+/g, " ").trim().toLowerCase().replace(/\.$/, "");
const abs = (name, domain) => (name === "@" ? domain : `${name}.${domain}`.toLowerCase());
const rel = (fqdn, domain) => (fqdn === domain ? "@" : fqdn.endsWith(`.${domain}`) ? fqdn.slice(0, -(domain.length + 1)) : fqdn);
const show = (r) => (r.type === "MX" ? `${r.priority} ${r.value}` : r.value);
export const GENERATED_VALUE = "(generated by the email platform)";

/**
 * Build [{ type, name, fqdn, action: "add"|"replace"|"delete", before[], after[], reason, changes, blocked, blockedReason, records }]
 * from the plan's day-one records. `before` is every existing record at that name and type (from the
 * upload, or live DNS for the names read from it), so the technician sees exactly what's there now.
 */
export function buildChangeSet(base, plan, domain) {
  const d = domain.toLowerCase();
  const groups = new Map();
  for (const it of plan.items || []) {
    for (const r of it.records || []) {
      if (r.zone || r.later) continue; // another domain's record, or a later stage
      const fqdn = abs(r.name, d);
      const key = `${fqdn}|${r.type}`;
      if (!groups.has(key)) groups.set(key, { type: r.type, fqdn, name: r.name, items: new Set(), records: [] });
      const g = groups.get(key);
      g.items.add(it.title);
      g.records.push(r);
    }
  }
  const out = [];
  for (const g of groups.values()) {
    const before = base.filter((x) => x.name === g.fqdn && x.type === g.type).map(show);
    let after = [...before];
    for (const r of g.records) {
      const value = r.generated ? GENERATED_VALUE : r.value;
      if (r.action === "Delete") {
        after = after.filter((v) => norm(v) !== norm(r.value));
      } else if (r.action === "Replace") {
        const i = after.findIndex((v) => norm(v) === norm(r.current));
        if (i >= 0) after.splice(i, 1, value);
        else after.push(value);
      } else if (!after.some((v) => norm(v) === norm(value))) {
        after.push(value);
      }
    }
    const actions = new Set(g.records.map((r) => r.action));
    const action = actions.size === 1 && actions.has("Delete") ? "delete" : actions.size === 1 && actions.has("Add") ? "add" : "replace";
    const blocked = g.records.find((r) => r.blocked === true) || g.records.find((r) => r.blocked === "unverified");
    out.push({
      type: g.type,
      name: rel(g.fqdn, d),
      fqdn: g.fqdn,
      action,
      before,
      after,
      reason: [...g.items].join("; "),
      notes: g.records.map((r) => r.note).filter(Boolean),
      changes: g.records.flatMap((r) => r.changes || []),
      blocked: blocked ? blocked.blocked : false,
      blockedReason: blocked ? blocked.note : null,
      generated: g.records.some((r) => r.generated),
    });
  }
  return out;
}

/** Stable fingerprint of what the technician is confirming. The server recomputes it on confirm. */
export function changeSetHash(changeSet) {
  const canonical = changeSet.map((e) => [e.type, e.fqdn, e.action, e.before, e.after, e.blocked || false]);
  return createHash("sha256").update(JSON.stringify(canonical)).digest("hex");
}

/** Records touched by a change set: a replaced value counts once, an extra added or removed value counts too. */
export function recordsTouched(changeSet) {
  let n = 0;
  for (const e of changeSet) {
    const b = new Set(e.before.map(norm));
    const a = new Set(e.after.map(norm));
    const removed = [...b].filter((v) => !a.has(v)).length;
    const added = [...a].filter((v) => !b.has(v)).length;
    n += Math.max(removed, added);
  }
  return n;
}
