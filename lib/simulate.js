// Dry run of a fix plan: apply the "publish now" DNS changes to a copy of the client's records,
// re-run every check against the copy, and refuse (blocked) if anything would get worse or if
// any record unrelated to email authentication would be touched.

import { runScan } from "./scan.js";
import { zoneResolver, isEmailAuthRecord, dkimSelectors } from "./zone.js";
import { parseDmarc, dnsReachable, deadSpfIncludes } from "./checks/email.js";

const RANK = { fail: 0, warn: 1, unknown: 1, pass: 2 };
const norm = (v) => String(v ?? "").replace(/\s+/g, " ").trim().toLowerCase().replace(/\.$/, "");
const abs = (name, domain) => (name === "@" ? domain : `${name}.${domain}`.toLowerCase());
const spfTerms = (r) =>
  String(r).trim().split(/\s+/).slice(1).filter((t) => !/^[+\-~?]?all$/i.test(t) && !/^exp=/i.test(t)).map((t) => t.replace(/^\+/, "").toLowerCase().replace(/^redirect=/, "include:"));
const isSpf = (r, d) => r.name === d && r.type === "TXT" && /^v=spf1(\s|$)/i.test(r.value);
const isDmarc = (r, d) => r.name === `_dmarc.${d}` && r.type === "TXT" && /^v=DMARC1/i.test(r.value);
const key = (r) => `${r.name}|${r.type}|${r.type === "MX" ? `${r.priority} ` : ""}${norm(r.value)}`;

/**
 * Build a stand-in for the parts of a zone we can see publicly, for clients who haven't uploaded
 * their records. Only the names we read are "owned"; everything else still comes from live DNS.
 */
export async function liveBaseRecords(domain, resolver, report) {
  const d = domain.toLowerCase();
  const records = [];
  const owned = new Set([`${d}|TXT`, `${d}|MX`, `_dmarc.${d}|TXT`]);
  const txt = async (name) => {
    try {
      return (await resolver.resolveTxt(name)).map((c) => c.join(""));
    } catch {
      return [];
    }
  };
  for (const v of await txt(d)) records.push({ name: d, type: "TXT", ttl: null, value: v });
  try {
    for (const m of await resolver.resolveMx(d)) records.push({ name: d, type: "MX", ttl: null, priority: m.priority, value: String(m.exchange).toLowerCase().replace(/\.$/, "") });
  } catch {
    /* no MX */
  }
  for (const v of await txt(`_dmarc.${d}`)) records.push({ name: `_dmarc.${d}`, type: "TXT", ttl: null, value: v });
  for (const sel of report.checks.find((c) => c.id === "dkim")?.data?.found || []) {
    const name = `${sel}._domainkey.${d}`;
    owned.add(`${name}|TXT`);
    for (const v of await txt(name)) records.push({ name, type: "TXT", ttl: null, value: v });
  }
  return { records, owned };
}

/** Apply the plan's day-one changes to a copy of `base`. Returns the new records plus a per-change log. */
export function applyPlan(base, plan, domain) {
  const d = domain.toLowerCase();
  let records = base.map((r) => ({ ...r }));
  const changes = [];
  const assumptions = [];
  const blockers = [];
  const warnings = [];

  for (const it of plan.items) {
    for (const r of it.records || []) {
      if (r.zone) continue; // goes on another domain (e.g. the DMARC report authorization)
      const name = abs(r.name, d);
      const entry = { item: it.title, action: r.action, type: r.type, name: r.name, from: r.current || (r.action === "Delete" ? r.value : null), to: r.action === "Delete" ? null : r.value };
      if (r.later) {
        changes.push({ ...entry, status: "later", note: r.note });
        continue;
      }
      if (r.blocked === "unverified") {
        // Simulated so the dry run still shows its effect, but it stays locked until checked by hand.
        warnings.push(`${it.title}: ${r.note}`);
        entry.unverified = true;
      } else if (r.blocked) {
        changes.push({ ...entry, status: "blocked", note: r.note });
        blockers.push(`${it.title}: ${r.note}`);
        continue;
      }
      if (r.generated) {
        if (name.includes("<") || !/_domainkey/.test(name)) {
          changes.push({ ...entry, status: "not-simulated", note: r.note || "Value not known yet" });
          if (!/_domainkey/.test(name)) blockers.push(`${it.title}: there's no record to publish yet (${r.value})`);
          else assumptions.push(`${it.title}: the key name is chosen in the email platform, so it wasn't simulated.`);
          continue;
        }
        // A DKIM key only the platform can generate: model it as published so the "after" state is realistic.
        records = records.filter((x) => !(x.name === name && (x.type === "TXT" || x.type === "CNAME")));
        records.push({ name, type: "TXT", ttl: null, value: "v=DKIM1; k=rsa; p=SIMULATED-KEY", simulated: true });
        changes.push({ ...entry, status: "assumed", note: "Assumed published as generated by the platform" });
        assumptions.push(`${it.title}: assumes the ${r.type} record at ${r.name} is published exactly as the email platform generates it.`);
        continue;
      }
      if (r.action === "Delete" || r.action === "Replace") {
        const target = norm(r.action === "Delete" ? r.value : r.current);
        const idx = records.findIndex((x) => x.name === name && x.type === r.type && norm(x.value) === target);
        if (idx < 0) {
          changes.push({ ...entry, status: "conflict", note: "The current value in the records doesn't match what the plan expects to replace. Re-build the plan from up-to-date records." });
          blockers.push(`${it.title}: the record to ${r.action.toLowerCase()} at ${r.name} wasn't found with the expected value.`);
          continue;
        }
        records.splice(idx, 1);
        if (r.action === "Delete") {
          changes.push({ ...entry, status: "applied" });
          continue;
        }
      }
      if (!records.some((x) => x.name === name && x.type === r.type && norm(x.value) === norm(r.value))) {
        records.push({ name, type: r.type, ttl: null, value: r.value });
      }
      changes.push({ ...entry, status: "applied" });
    }
  }
  return { records, changes, assumptions, blockers, warnings };
}

const summarize = (report) => ({
  grade: report.grade,
  score: report.score,
  checks: report.checks.map((c) => ({ id: c.id, title: c.title, status: c.status, summary: c.summary })),
});

/**
 * Run the dry run. `deps` are the live network functions (cached, so the website checks aren't
 * repeated); `before` is the report the plan was built from.
 */
export async function simulatePlan({ domain, base, owned = null, authoritative, plan, before, deps }) {
  const d = domain.toLowerCase();
  const { records: after, changes, assumptions, blockers, warnings } = applyPlan(base, plan, d);
  const live = await dnsReachable(deps.resolver);
  if (!live) warnings.push("Live DNS couldn't be reached, so third-party SPF includes and the SPF lookup count weren't checked. Re-run the dry run, or check the new SPF record with an SPF checker before publishing.");

  const resolver = zoneResolver(after, d, deps.resolver, { authoritative, owned: owned && new Set([...owned, ...changes.map((c) => `${abs(c.name, d)}|${c.type}`)]) });
  const selectors = [...new Set([...dkimSelectors(base, d), ...dkimSelectors(after, d)])];
  const afterReport = await runScan(d, { ...deps, resolver, dkimSelectors: selectors, zoneAuthoritative: authoritative });

  // 1. Nothing may get worse.
  const comparisons = before.checks.map((b) => {
    const a = afterReport.checks.find((c) => c.id === b.id) || {};
    const delta = b.status in RANK && a.status in RANK ? Math.sign(RANK[a.status] - RANK[b.status]) : 0;
    return { id: b.id, title: b.title, before: b.status, after: a.status, delta, afterSummary: a.summary };
  });
  for (const c of comparisons) if (c.delta < 0) blockers.push(`${c.title} would get worse: ${c.before} → ${c.after}.`);

  // 2. Exactly one SPF and one DMARC record afterwards.
  if (after.filter((r) => isSpf(r, d)).length > 1) blockers.push("There would be more than one SPF record. Receivers treat that as broken.");
  if (after.filter((r) => isDmarc(r, d)).length > 1) blockers.push("There would be more than one DMARC record. Receivers ignore all of them.");

  // 3. SPF stays within the lookup limit and keeps every sender it allowed before.
  const spfAfter = afterReport.checks.find((c) => c.id === "spf");
  if (spfAfter?.data?.lookups > 10) blockers.push(`SPF would need ${spfAfter.data.lookups} DNS lookups (limit 10).`);
  else if (live && after.some((r) => isSpf(r, d)) && spfAfter?.data?.lookups == null) warnings.push("Couldn't confirm the SPF lookup count against live DNS. Check it with an SPF checker before publishing.");
  if (live) {
    for (const r of after.filter((x) => isSpf(x, d))) {
      const dead = await deadSpfIncludes(resolver, r.value);
      if (dead.length) blockers.push(`SPF includes ${dead.join(", ")}, which ${dead.length > 1 ? "have" : "has"} no SPF record. That breaks SPF for the whole domain.`);
    }
  }
  const beforeTerms = new Set(base.filter((r) => isSpf(r, d)).flatMap((r) => spfTerms(r.value)));
  const afterTerms = new Set(after.filter((r) => isSpf(r, d)).flatMap((r) => spfTerms(r.value)));
  // Removals the plan lists explicitly, with a reason (ptr, true duplicates), are allowed.
  const explained = new Set(
    plan.items.flatMap((it) => (it.records || []).flatMap((r) => (r.changes || []).filter((c) => c.op === "remove").map((c) => c.term.replace(/^\+/, "").toLowerCase()))),
  );
  const dropped = [...beforeTerms].filter((t) => !afterTerms.has(t) && !explained.has(t));
  if (dropped.length) blockers.push(`SPF would stop allowing: ${dropped.join(", ")}.`);

  // 4. DMARC keeps the client's report addresses and doesn't jump straight to enforcement.
  const dmBefore = base.find((r) => isDmarc(r, d));
  const dmAfter = after.find((r) => isDmarc(r, d));
  if (dmBefore && dmAfter) {
    const tb = parseDmarc(dmBefore.value);
    const ta = parseDmarc(dmAfter.value);
    const lost = (tb.rua || "").split(",").map((x) => x.trim().toLowerCase()).filter(Boolean).filter((a) => !(ta.rua || "").toLowerCase().includes(a));
    if (lost.length) blockers.push(`DMARC would stop sending reports to ${lost.join(", ")}.`);
    const strict = { none: 0, quarantine: 1, reject: 2 };
    if ((strict[ta.p] ?? 0) > (strict[tb.p] ?? 0)) blockers.push(`DMARC policy would tighten on day one (p=${tb.p || "none"} → p=${ta.p}). Tighten only after reports confirm every sender passes.`);
  } else if (!dmBefore && dmAfter && !/p\s*=\s*none/i.test(dmAfter.value)) {
    blockers.push("A brand-new DMARC record must start at p=none (monitor only).");
  }

  // 5. Nothing outside email authentication is touched (website, MX, verification records…).
  const others = (rs) => rs.filter((r) => !isEmailAuthRecord(r, d)).map(key).sort();
  const ob = others(base);
  const oa = others(after);
  const removed = ob.filter((k) => !oa.includes(k));
  const added = oa.filter((k) => !ob.includes(k));
  if (removed.length || added.length) blockers.push(`Records unrelated to email authentication would change: ${[...removed.map((k) => `removed ${k}`), ...added.map((k) => `added ${k}`)].join("; ")}.`);

  return {
    verdict: blockers.length ? "blocked" : warnings.length ? "check" : "safe",
    mode: authoritative ? "zone" : "public",
    blockers,
    warnings,
    assumptions,
    changes,
    comparisons,
    before: summarize(before),
    after: summarize(afterReport),
    export: exportChanges(changes, d),
  };
}

/** The day-one changes only (never a full zone), as a BIND fragment and a CSV. */
export function exportChanges(changes, domain) {
  const d = domain.toLowerCase();
  const fq = (n) => `${abs(n, d)}.`;
  const quote = (v) => `"${String(v).replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
  const val = (type, v) => (type === "TXT" ? quote(v) : type === "CNAME" ? `${String(v).replace(/\.$/, "")}.` : v);
  const now = changes.filter((c) => ["applied", "assumed"].includes(c.status));
  const zone = [
    `; Day-one DNS changes for ${d}, from the NWIM PM fix plan.`,
    "; Lines starting with ; are instructions, not records. Apply by hand, or import ONLY the",
    "; uncommented lines with your DNS host's import tool. This is not a full zone: never replace a zone with it.",
    "",
  ];
  for (const c of now) {
    if (c.action === "Delete") zone.push(`; DELETE  ${fq(c.name)} ${c.type} ${val(c.type, c.from)}`);
    else if (c.status === "assumed") zone.push(`; ADD     ${fq(c.name)} ${c.type} <value generated by the email platform>`);
    else {
      if (c.action === "Replace") zone.push(`; REPLACE ${fq(c.name)} ${c.type} ${val(c.type, c.from)}  with:`);
      zone.push(`${fq(c.name)} 3600 IN ${c.type} ${val(c.type, c.to)}`);
    }
  }
  const csvq = (v) => (v == null ? "" : `"${String(v).replace(/"/g, '""')}"`);
  const csv = ["Action,Type,Name,Current value,New value", ...now.map((c) => [c.action, c.type, c.name, csvq(c.from), c.status === "assumed" ? csvq("(generated by the email platform)") : csvq(c.to)].join(","))];
  return { zone: `${zone.join("\n")}\n`, csv: `${csv.join("\n")}\n` };
}
